CREATE TABLE user_types (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(50) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE UNIQUE INDEX user_types_name_active_idx ON user_types (lower(name)) WHERE deleted_at IS NULL;

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL,
  username varchar(50) NOT NULL,
  email varchar(255) NOT NULL,
  password varchar(255) NOT NULL,
  user_type bigint NOT NULL REFERENCES user_types(id),
  is_active boolean NOT NULL DEFAULT true,
  last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE UNIQUE INDEX users_username_active_idx ON users (lower(username)) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX users_email_active_idx ON users (lower(email)) WHERE deleted_at IS NULL;

CREATE TABLE sex (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(50) NOT NULL UNIQUE);
CREATE TABLE sexual_orientation (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(100) NOT NULL UNIQUE);

CREATE TABLE clients (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL,
  social_name varchar(150),
  birth_date date NOT NULL,
  sex_id bigint NOT NULL REFERENCES sex(id),
  sexual_orientation_id bigint REFERENCES sexual_orientation(id),
  cpf varchar(14),
  telefone varchar(20) NOT NULL,
  email varchar(255),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  marketing_consent boolean NOT NULL DEFAULT false,
  marketing_consent_at timestamptz,
  marketing_consent_recorded_by bigint REFERENCES users(id),
  marketing_consent_version text,
  marketing_consent_withdrawn_at timestamptz,
  marketing_consent_withdrawn_by bigint REFERENCES users(id)
);
CREATE UNIQUE INDEX idx_clients_cpf_active ON clients (cpf) WHERE cpf IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE address (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id bigint NOT NULL REFERENCES clients(id),
  cep varchar(8) NOT NULL,
  city varchar(100) NOT NULL,
  state char(2) NOT NULL,
  street varchar(150) NOT NULL,
  neighborhood varchar(100) NOT NULL,
  number varchar(20) NOT NULL,
  complement varchar(100),
  reference_point varchar(200),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE TABLE menus (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL,
  description varchar(150),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  description text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE TABLE products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(50),
  name varchar(150) NOT NULL,
  description text,
  category_id bigint REFERENCES categories(id),
  sale_price numeric(10,2) NOT NULL,
  cost_price numeric(10,2) NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  id_file bigint
);
CREATE TABLE menu_procuct (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  menu_id bigint NOT NULL REFERENCES menus(id),
  product_id bigint NOT NULL REFERENCES products(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
CREATE UNIQUE INDEX menu_product_active_idx ON menu_procuct (menu_id, product_id) WHERE deleted_at IS NULL;
CREATE TABLE file_product (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_product bigint NOT NULL REFERENCES products(id),
  file_data bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);
